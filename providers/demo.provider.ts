/**
 * Demo data provider (§73).
 *
 * ScoutIQ must be fully usable straight after `docker compose up`, with no API
 * keys and no internet access. This provider fabricates a small but complete
 * league: teams, squads, matches, and enough events to drive metrics, DNA,
 * roles, similarity, heatmaps, shot maps and PDF reports.
 *
 * Everything it produces is labelled DEMO DATA in the database and in the UI.
 * It is invented, not observed, and must never be mistaken for real football.
 */

const DEMO_LABEL = 'DEMO DATA';

/**
 * Deterministic PRNG (mulberry32): the same seed produces the same league on
 * every machine, which makes demo output comparable across installations and
 * usable in tests.
 */
function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

interface DemoSquadPlayer {
  externalId: string;
  firstName: string;
  lastName: string;
  position: string;
  teamExternalId: string;
  /** 0-1 quality knob that shapes the generated events. */
  quality: number;
}

